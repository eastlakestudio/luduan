    private val cache = HashMap<String, String>()

    /** 获取指定单字的带声调拼音 */
    fun pinyin(char: String): String {
        cache[char]?.let { return it }
        val py = dict[char] ?: char
        cache[char] = py
        return py
    }

    private val toneMap = mapOf(
        'ā' to 'a', 'á' to 'a', 'ǎ' to 'a', 'à' to 'a',
        'ē' to 'e', 'é' to 'e', 'ě' to 'e', 'è' to 'e',
        'ī' to 'i', 'í' to 'i', 'ǐ' to 'i', 'ì' to 'i',
        'ō' to 'o', 'ó' to 'o', 'ǒ' to 'o', 'ò' to 'o',
        'ū' to 'u', 'ú' to 'u', 'ǔ' to 'u', 'ù' to 'u',
        'ǖ' to 'v', 'ǘ' to 'v', 'ǚ' to 'v', 'ǜ' to 'v', 'ü' to 'v'
    )

    /** 获取指定单字的无声调拼音 */
    fun pinyinWithoutTone(char: String): String =
        pinyin(char).map { toneMap[it] ?: it }.joinToString("").lowercase()
